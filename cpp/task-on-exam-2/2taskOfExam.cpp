#include <iostream>
using namespace std;

/* Програма не використовує файлові змінні(ifstream / ofstream).Копіювання
відбувається через перенаправлення стандартних потоків на рівні операційної системи.

як запустити :
	назва_програми.exe < input.txt > output.txt

	Символ '<' перенаправляє файл input.txt у потік cin(замість клавіатури).
	Символ '>' перенаправляє потік cout у файл output.txt (замість екрану).
	Цикл посимвольно переносить дані, поки не досягне кінця файлу.
	*/

int main()
{
	char ch;

	// Посимвольно читаємо з перенаправленого cin і пишемо в cout
	while (cin.get(ch)) {
		cout.put(ch);
	}

	return 0;
}

